// ---- Health ----
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", message: "Database is not responding." });
  }
});

app.use("/api/records", require("./routes/records"));

// ---- Unknown routes ----
app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

// ---- Error handler (four parameters) ----
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed" || error instanceof SyntaxError) {
    return res.status(400).json({ message: "Malformed JSON in request body." });
  }
  if (error.status && error.status < 500) {
    return res.status(error.status).json({ message: error.message });
  }
  console.error(error);
  res.status(500).json({ message: "Unexpected server error. Please try again." });
});

const port = process.env.PORT || 3000;
pool.initDb()
  .then(() => {
    app.listen(port, "0.0.0.0", () => console.log(`Server listening on port ${port}`));
  })
  .catch((error) => {
    console.error("Could not initialise the database:", error.message);
    process.exit(1);
  });
